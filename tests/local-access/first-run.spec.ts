import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { readFile } from 'node:fs/promises'
import { join } from 'node:path'

const vars = Object.fromEntries((await readFile(join(process.env.PENCIL_FRESH_COPY!, '.dev.vars'), 'utf8')).trim().split('\n').map(line => line.split('=')))
const owner = vars.SEED_ADMIN_EMAIL
async function accessible(page: import('@playwright/test').Page) {
  await page.evaluate(() => document.fonts.ready)
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
test('BASE-ACCESS-001 BASE-PUBLIC-003 DASH-001 WS-001 FLOW-002 first owner and local mail work in an empty fresh install', async ({ page }, info) => {
  await page.goto('/signin')
  await expect(page.getByRole('heading', { name: 'Set up Pencil' })).toBeVisible()
  await accessible(page)
  await page.getByLabel('Your name').fill('Workspace owner')
  await page.getByLabel('Setup token').fill('incorrect-setup-token')
  await page.getByRole('button', { name: 'Set up the first owner' }).click()
  await expect(page.getByRole('alert')).toContainText('not accepted')
  await page.getByLabel('Setup token').fill(vars.SETUP_TOKEN)
  await page.getByRole('button', { name: 'Set up the first owner' }).click()
  await expect(page).toHaveURL(/\/app$/)
  expect(await (await page.request.get('/api/app/dashboard')).json()).toEqual([])
  await accessible(page)
  await page.screenshot({ path: join(process.env.PENCIL_ACCESS_EVIDENCE!, `${info.project.name}-empty-dashboard.png`) })
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible()
  expect(await page.getByLabel('Setup token').count()).toBe(0)
  const heading = await page.getByRole('heading', { name: 'Sign in', exact: true }).boundingBox()
  const explanation = await page.getByText('Enter your operator email').boundingBox()
  expect(heading!.y + heading!.height).toBeLessThanOrEqual(explanation!.y)
  await accessible(page)
  await page.getByLabel('Operator email').fill(owner)
  await page.getByRole('button', { name: 'Send magic link' }).click()
  await expect(page.getByText('The link works once', { exact: false })).toBeVisible()
  await page.getByRole('link', { name: 'Open the local outbox' }).click()
  await accessible(page)
  await page.locator('article').filter({ hasText: owner }).getByRole('link', { name: 'Read message' }).first().click()
  await accessible(page)
  await page.getByRole('link', { name: 'Open this link' }).click()
  await expect(page.getByRole('heading', { name: 'Confirm sign-in to Pencil' })).toBeVisible()
  await accessible(page)
  expect(await page.locator('body').evaluate(element => getComputedStyle(element).fontFamily)).toContain('system-ui')
  await page.screenshot({ path: join(process.env.PENCIL_ACCESS_EVIDENCE!, `${info.project.name}-confirm.png`) })
  await page.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page).toHaveURL(/\/app$/)
  expect(await (await page.request.get('/api/app/dashboard')).json()).toEqual([])
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await page.getByLabel('Time zone', { exact: true }).fill('brisbane')
  await page.getByRole('button', { name: 'Australia/Brisbane', exact: true }).click()
  await page.getByRole('button', { name: 'Save workspace settings' }).click()
  await expect(page.getByRole('status')).toContainText('saved')
  await page.getByLabel('Time zone', { exact: true }).fill('invalid-zone')
  await page.getByRole('button', { name: 'Save workspace settings' }).click()
  await expect(page.getByRole('alert')).toContainText('Australia/Brisbane')
  expect((await (await page.request.get('/api/app/workspace')).json()).timeZone).toBe('Australia/Brisbane')
  await page.getByLabel('Time zone', { exact: true }).fill('Australia/Brisbane')
  await page.getByRole('link', { name: 'Flows', exact: true }).click()
  await page.getByRole('button', { name: 'Blank flow', exact: true }).click()
  await page.getByLabel('Flow name').fill('First flow')
  await page.getByLabel('Public link', { exact: true }).fill('first-flow')
  const businessName = page.getByLabel('Business name', { exact: true })
  await expect(businessName).toBeVisible()
  await expect(businessName).toHaveValue('')
  await expect(businessName).toHaveJSProperty('required', true)
  await expect(page.getByRole('button', { name: 'Create draft flow' })).toBeDisabled()
  await businessName.fill('North Studio')
  await expect(page.getByRole('button', { name: 'Create draft flow' })).toBeEnabled()
  await page.getByRole('button', { name: 'Create draft flow' }).click()
  const add = page.getByRole('button', { name: 'Add question', exact: true })
  await expect(add).toBeVisible()
  const savedBrand = await page.request.get('/api/app/brand')
  expect(savedBrand.ok()).toBe(true)
  expect(await savedBrand.json()).toMatchObject({ name: 'North Studio', configured: true })
  const guidance = page.getByText('Start with a question, then add a completion screen.')
  await expect(guidance).toBeVisible()
  expect((await add.boundingBox())!.y).toBeLessThan(info.project.use.viewport!.height)
  expect((await guidance.boundingBox())!.y).toBeLessThan(info.project.use.viewport!.height)
  await accessible(page)
  await page.screenshot({ path: join(process.env.PENCIL_ACCESS_EVIDENCE!, `${info.project.name}-empty-builder.png`) })
  await page.goto('/auth/confirm?token=expired')
  await expect(page.getByRole('link', { name: 'Request a new link' })).toHaveAttribute('href', '/signin')
  await accessible(page)
  await page.screenshot({ path: join(process.env.PENCIL_ACCESS_EVIDENCE!, `${info.project.name}-expired.png`) })
})
