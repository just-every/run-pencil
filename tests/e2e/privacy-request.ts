import type { Page, TestInfo } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { expect } from './fixtures'
import type { ScenarioCall } from '../results-scenario'
import AxeBuilder from '@axe-core/playwright'

export async function privacyRequestBrowser(page: Page, call: ScenarioCall, info: TestInfo, capture: (name: string) => Promise<void>) {
  const mailbox = ['synthetic-pencil-browser-privacy', 'example.test'].join('@')
  const contact = await call<{id:string}>('/api/app/distribution/contacts', { name: 'Jordan Patel', email: mailbox, mobile: '+61412345678', fields: { organisation: 'Aurora Coffee' } })
  const flow = await call<{id:string}>('/api/app/flows', { title: 'Customer privacy request', slug: 'privacy-' + crypto.randomUUID().slice(0, 8) })
  const base = `/api/app/flows/${flow.id}`, draft = () => call<any>(base + '/draft')
  for (const step of [{ kind: 'question', questionType: 'email', prompt: 'Your email', required: true }, { kind: 'question', questionType: 'long_text', prompt: 'Your feedback', required: true }, { kind: 'completion', questionType: null, prompt: 'Thank you.' }]) await call(base + '/draft/steps', { expectedVersion: (await draft()).flow.draftVersion, step })
  const current = await draft()
  await call(base + '/publish', { expectedVersion: current.flow.draftVersion })
  const session = await call<any>(`/api/public/flows/${current.flow.slug}/sessions`, { deviceClass: 'desktop', source: 'direct' })
  const response = await call<any>(`/api/public/flows/${current.flow.slug}/responses`, { ...session, idempotencyKey: 'synthetic-pencil-browser-' + crypto.randomUUID(), answers: current.steps.filter((step:any) => step.kind === 'question').map((step:any) => ({ stepId: step.id, value: step.questionType === 'email' ? mailbox : 'The afternoon workshop was welcoming.' })) })
  if (response.disposition === 'quarantined') await call(`/api/app/responses/${response.responseId}/release`, {})
  await page.goto('/app/settings')
  const panel = page.getByRole('region', { name: 'Privacy requests', exact: true })
  await panel.getByText('Find, export or erase linked data', { exact: true }).click()
  await panel.getByLabel('Email or phone', { exact: true }).fill(mailbox)
  await panel.getByRole('button', { name: 'Find linked data', exact: true }).click()
  await expect(panel.getByText('1 responses', { exact: true })).toBeVisible()
  await expect(panel.getByText('1 contacts', { exact: true })).toBeVisible()
  await expect(panel.getByText('Customer privacy request', { exact: true })).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Confirm privacy erasure', exact: true })).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const small = await panel.locator('*').evaluateAll(elements => elements.filter(element => element.textContent?.trim() && getComputedStyle(element).display !== 'none' && element.getClientRects().length && parseFloat(getComputedStyle(element).fontSize) < 13).map(element => element.tagName))
  expect(small).toEqual([])
  expect((await new AxeBuilder({ page }).include('[aria-labelledby="privacy-requests-title"]').analyze()).violations).toEqual([])
  await panel.screenshot({ path: `test-results/${info.project.name}-privacy-found.png` })
  await capture('privacy-found')
  const downloadPromise = page.waitForEvent('download')
  await panel.getByRole('button', { name: 'Download portable JSON' }).click()
  const download = await downloadPromise, file = await download.path()
  expect(file).toBeTruthy()
  const bundle = JSON.parse(await readFile(file!, 'utf8'))
  expect(bundle.contacts.map((row:any) => row.id)).toContain(contact.id)
  expect(bundle.responses.map((row:any) => row.id)).toContain(response.responseId)
  expect(JSON.stringify(bundle)).toContain('The afternoon workshop was welcoming.')
  await panel.getByLabel('I confirm erasure of all linked data', { exact: true }).check()
  await expect(panel.getByRole('button', { name: 'Confirm privacy erasure', exact: true })).toBeEnabled()
  await capture('privacy-confirmation')
  await panel.getByRole('button', { name: 'Confirm privacy erasure', exact: true }).click()
  await expect(panel.getByRole('heading', { name: 'Privacy erasure completed', exact: true })).toBeVisible()
  await expect(panel.getByLabel('Email or phone', { exact: true })).toHaveValue('')
  await panel.screenshot({ path: `test-results/${info.project.name}-privacy-erased.png` })
  await capture('privacy-erased')
  await panel.getByLabel('Email or phone', { exact: true }).fill(mailbox)
  await panel.getByRole('button', { name: 'Find linked data', exact: true }).click()
  await expect(panel.getByText('0 responses', { exact: true })).toBeVisible()
  await expect(panel.getByText('0 contacts', { exact: true })).toBeVisible()
  expect((await call<any>(base + '/ledger')).rows).toHaveLength(0)
}
