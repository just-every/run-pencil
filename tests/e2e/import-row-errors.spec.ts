import AxeBuilder from '@axe-core/playwright'
import { contract } from './contract'
import { expect } from './fixtures'
import { signInEmptyWorkspace } from './authoring-helpers'

contract(['IMPORT-002', 'IMPORT-003', 'BASE-PUBLIC-003'], 'every invalid-row diagnostic remains reachable across accessible error pages', async ({ page }, info) => {
  await page.setViewportSize(info.project.name === 'desktop' ? { width: 1440, height: 900 } : { width: 390, height: 844 })
  await signInEmptyWorkspace(page)
  await page.getByRole('link', { name: 'Import a form' }).click()
  const definition = JSON.stringify({ title: 'Invalid row review', fields: [{ ref: 'answer', title: 'Answer', type: 'yes_no' }] })
  const csv = 'Answer,Submit Date\n' + Array.from({ length: 205 }, () => 'x,2026-09-12 10:03:00').join('\n')
  await page.getByLabel('Form definition JSON').setInputFiles({ name: 'form.json', mimeType: 'application/json', buffer: Buffer.from(definition) })
  await page.getByLabel('Response CSV (optional)').setInputFiles({ name: 'responses.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
  await page.getByRole('button', { name: 'Review import', exact: true }).click()
  const errors = page.getByRole('region', { name: 'Every row error (205)' })
  await expect(errors.getByRole('listitem')).toHaveCount(100)
  await expect(errors.getByText('Row 2, Answer: Use 1/0 or true/false.', { exact: true })).toBeVisible()
  await expect(errors.getByRole('button', { name: 'Previous errors' })).toBeDisabled()
  await errors.getByRole('button', { name: 'Next errors' }).click()
  await expect(errors.getByText('Row 102, Answer: Use 1/0 or true/false.', { exact: true })).toBeVisible()
  await errors.getByRole('button', { name: 'Next errors' }).click()
  await expect(errors.getByRole('listitem')).toHaveCount(5)
  await expect(errors.getByText('Row 206, Answer: Use 1/0 or true/false.', { exact: true })).toBeVisible()
  await expect(errors.getByRole('button', { name: 'Next errors' })).toBeDisabled()
  await errors.getByRole('button', { name: 'First errors' }).click()
  await expect(errors.getByText('Row 2, Answer: Use 1/0 or true/false.', { exact: true })).toBeVisible()
  await errors.getByRole('button', { name: 'Last errors' }).click()
  await expect(errors.getByRole('listitem')).toHaveCount(5)
  await errors.getByRole('button', { name: 'Previous errors' }).click()
  await expect(errors.getByRole('listitem')).toHaveCount(100)
  await page.getByRole('checkbox').check()
  await expect(page.getByRole('button', { name: 'Import reviewed form' })).toBeDisabled()
  expect(await (await page.request.get('/api/app/imports')).json()).toEqual([])
  await page.screenshot({ path: info.outputPath('complete-row-errors.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect((await new AxeBuilder({ page }).analyze()).violations.filter(v => ['serious', 'critical'].includes(v.impact ?? ''))).toEqual([])
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(await (await page.request.get('/api/app/imports')).json()).toEqual([])
})
