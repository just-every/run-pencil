  await page.getByRole('combobox', { name: 'Date order', exact: true }).selectOption('DMY')
  await page.getByLabel('Imported form title').fill('Google historical CSV')
  await googleReview(page)
  await page.getByRole('combobox', { name: 'Question type: Answer (column 2)', exact: true }).selectOption('long_text')
