import AxeBuilder from '@axe-core/playwright'
import { contract } from './contract'
import { expect } from './fixtures'
import { signInEmptyWorkspace } from './authoring-helpers'
import { downloadedText } from './export-helpers'

contract(["FIELD-014","FIELD-019"], 'builds reviewed country and bulk lists and collects a keyboard-selected searchable dropdown', async ({ page }, info) => {
  await signInEmptyWorkspace(page)
  await page.getByRole('button', { name: 'Blank flow', exact: true }).click()
  await page.getByLabel('Flow name').fill(`Regional office onboarding ${info.project.name}`)
  await page.getByRole('button', { name: 'Create draft flow' }).click()
  await expect(page).toHaveURL(/\/flows\/[^/]+\/builder$/)
  const flowId = /flows\/([^/]+)\//.exec(page.url())![1]
  const rail = page.getByRole('complementary', { name: 'Flow steps' })
  const editor = page.getByRole('complementary', { name: 'Step settings' })
  await rail.getByRole('button', { name: 'Add question', exact: true }).click()
  await editor.getByLabel('Question type').selectOption('dropdown')
  await editor.getByLabel('Prompt', { exact: true }).fill('Where is your office?')
  await editor.getByLabel('Required response').check()
  await editor.getByText('Paste choices or insert a built-in list', { exact: true }).click()
  const lines = Array.from({ length: 300 }, (_, i) => `Regional office ${i + 1}`)
  lines[299] = lines[0]
  await editor.getByLabel('Choices to add').fill(lines.join('\n'))
  await expect(editor.getByText(/Line 300: duplicate/)).toBeVisible()
  await expect(editor.getByRole('button', { name: 'Add choices', exact: true })).toBeDisabled()
  await editor.getByLabel('Choices to add').fill('Local office\n\nBranch office')
  await expect(editor.getByText('Line 2 is blank.', { exact: true })).toBeVisible()
  await editor.getByLabel('Choices to add').fill('Café office')
  await editor.getByRole('button', { name: 'Add choices', exact: true }).click()
  await editor.getByLabel('Choice source').selectOption('countries')
  await editor.getByRole('button', { name: 'Add choices', exact: true }).click()
  await editor.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Saved.', { exact: true })).toBeVisible()
  await page.screenshot({ path: `test-results/${info.project.name}-long-choices-builder.png`, fullPage: true })
  await rail.getByRole('button', { name: 'Add completion screen', exact: true }).click()
  await editor.getByLabel('Prompt', { exact: true }).fill('Your office is registered')
  await editor.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Saved.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Publish', exact: true }).click()
  const publicUrl = await page.getByRole('region', { name: 'Share this flow' }).getByLabel('Public link', { exact: true }).inputValue()
  await page.goto(publicUrl)
  await page.getByLabel('Search options', { exact: true }).fill('cafe')
  await expect(page.getByRole('option', { name: 'Café office', exact: true })).toHaveCount(1)
  await expect(page.getByRole('status')).toContainText('1 matching option')
  await page.getByLabel('Search options', { exact: true }).fill('united')
  const select = page.getByRole('combobox', { name: 'Where is your office?' })
  await expect(select.getByRole('option', { name: /United States/ })).toHaveCount(1)
  const labels = await select.getByRole('option').allTextContents()
  expect(labels.slice(1).every(label => /united/i.test(label))).toBe(true)
  await select.focus()
  // Native select search uses the platform's keyboard control, retaining IDs.
  await page.keyboard.press('Home')
  for (let index = 0; index < labels.findIndex(label => label === 'United States'); index++) await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(select).not.toHaveValue('')
  await expect(select.locator('option:checked')).toHaveText('United States')
  await page.keyboard.press('Tab')
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `test-results/${info.project.name}-long-choices-respondent.png`, fullPage: true })
  await page.waitForTimeout(3200)
  await page.getByRole('button', { name: 'Submit response', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your office is registered' })).toBeVisible()
  await page.screenshot({ path: `test-results/${info.project.name}-long-choices-completed.png`, fullPage: true })
  await page.goto(`/app/flows/${flowId}/results`)
  const ledger = page.getByRole('region', { name: 'Response ledger' })
  const download = page.waitForEvent('download')
  await ledger.getByRole('button', { name: 'Export JSON' }).click()
  const exported = JSON.parse(await downloadedText(await download))
  expect(exported.responses).toHaveLength(1)
  expect(exported.responses[0].answers[0].value).toBe('US')
})
