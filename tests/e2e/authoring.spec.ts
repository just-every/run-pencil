import { appHeaders } from './api-headers'
import { expect, test } from './fixtures'
import { checkAuthoringLayout, signInEmptyWorkspace } from './authoring-helpers'
import { browserLogo } from './brand-helpers'

test('labels, one Save, real controls, reorder, branching, Share and a current dashboard', async ({ page, context }, info) => {
  test.setTimeout(120_000)
  await signInEmptyWorkspace(page)
  await checkAuthoringLayout(page)
  await page.getByRole('button', { name: 'Blank flow', exact: true }).click()
  const title = `Harbour Studio feedback ${info.project.name}`
  await page.getByLabel('Flow name').fill(title)
  await page.getByRole('button', { name: 'Create draft flow' }).click()
  await expect(page.getByRole('heading', { name: title })).toBeVisible()
  await checkAuthoringLayout(page)
  let unrelatedRouteLoads = 0
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/_serverFn/')) unrelatedRouteLoads++ })
  const rail = page.getByRole('complementary', { name: 'Flow steps' })
  const editor = page.getByRole('complementary', { name: 'Step settings' })
  const canvas = page.getByLabel('Draft question canvas')
  const save = async () => {
    await expect(editor.getByRole('button', { name: /^Save/ })).toHaveCount(1)
    await editor.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(page.getByText('Saved.', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeEnabled()
  }
  await rail.getByRole('button', { name: 'Add question', exact: true }).click()
  await editor.getByLabel('Prompt', { exact: true }).fill('Which path?')
  await editor.getByLabel('Question type').selectOption('single_choice')
  for (const label of ['More detail', 'Finish here']) {
    await editor.getByRole('button', { name: 'Choice', exact: true }).click()
    const index = label === 'More detail' ? 1 : 2
    await editor.getByLabel(`Choice ${index} label`).fill(label)
    await expect(editor.getByLabel(`Choice ${index} value`)).toBeHidden()
  }
  await canvas.getByRole('radio', { name: 'Finish here' }).click()
  await expect(canvas.getByRole('radio', { name: 'Finish here' })).toHaveAttribute('aria-checked', 'true')
  await save()
  const flowId = /flows\/([^/]+)\//.exec(page.url())![1]
  let draft = await (await page.request.get(`/api/app/flows/${flowId}/draft`)).json()
  expect(draft.choices.map((choice: { value: string }) => choice.value)).toEqual(['more-detail', 'finish-here'])
  const originalChoiceId = draft.choices[0].id
  await editor.getByLabel('Choice 1 label').fill('Tell us more')
  await editor.getByText('Advanced', { exact: true }).first().click()
  await expect(editor.getByLabel('Choice 1 value')).toHaveValue('more-detail')
  await editor.getByLabel('Choice 1 value').fill('detail')
  await editor.getByText('Advanced', { exact: true }).first().click()
  await save()
  await rail.getByRole('button', { name: 'Add question', exact: true }).click()
  await editor.getByLabel('Prompt', { exact: true }).fill('Your rating')
  await editor.getByLabel('Question type').selectOption('rating')
  await canvas.getByRole('radio', { name: '4 out of 5' }).click()
  await expect(canvas.getByRole('radio', { name: '4 out of 5' })).toHaveAttribute('data-selected', 'true')
  await save()
  await rail.getByRole('button', { name: 'Add question', exact: true }).click()
  await editor.getByLabel('Prompt', { exact: true }).fill('Any details?')
  await canvas.getByRole('textbox', { name: 'Any details?' }).fill('Preview only')
  await save()
  await rail.getByRole('button', { name: 'Add completion screen', exact: true }).click()
  await editor.getByLabel('Prompt', { exact: true }).fill('All done')
  await save()
  await editor.getByRole('button', { name: 'Move up', exact: true }).click()
  await expect(rail.locator('.step-button').nth(2)).toContainText('All done')
  await editor.getByRole('button', { name: 'Move down', exact: true }).click()
  await expect(rail.locator('.step-button').last()).toContainText('All done')
  await rail.getByRole('button', { name: /Which path/ }).click()
  await editor.getByLabel('Prompt', { exact: true }).fill('Choose your path')
  await editor.getByRole('button', { name: 'Add rule' }).click()
  await editor.getByLabel('Answer', { exact: true }).selectOption({ label: 'Finish here' })
  await editor.getByLabel('Then go to').selectOption({ label: 'All done' })
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeDisabled()
  await save()
  await checkAuthoringLayout(page)
  await page.screenshot({ path: `test-results/${info.project.name}-authoring-builder.png`, fullPage: true })
  expect(unrelatedRouteLoads).toBe(0)
  await page.reload()
  await expect(editor.getByLabel('Prompt', { exact: true })).toHaveValue('Choose your path')
  await expect(editor.getByLabel('Then go to')).toHaveValue(/.+/)
  unrelatedRouteLoads = 0
  draft = await (await page.request.get(`/api/app/flows/${flowId}/draft`)).json()
  expect(draft.choices[0].id).toBe(originalChoiceId)
  expect(draft.choices[0].value).toBe('detail')
  await page.getByRole('button', { name: 'Publish', exact: true }).click()
  await expect(page.getByText('Published. New visitors see this version.', { exact: true })).toBeVisible()
  const share = page.getByRole('region', { name: 'Share this flow' })
  await expect(share).toBeVisible()
  await checkAuthoringLayout(page)
  await expect(page.getByText('Unpublished changes', { exact: false })).toHaveCount(0)
  await page.bringToFront()
  await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: new URL(page.url()).origin })
  for (const label of ['Public link', 'Embed code']) {
    const value = await share.getByLabel(label, { exact: true }).inputValue()
    await share.getByRole('button', { name: `Copy ${label.toLowerCase()}` }).click()
    await expect(share.getByText(`${label} copied.`, { exact: true })).toBeVisible()
    expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(value)
  }
  await page.screenshot({ path: `test-results/${info.project.name}-authoring-share.png`, fullPage: true })
  const thirdPartyPreviewRequests: string[] = []
  const recordPreviewRequest = (request: import('@playwright/test').Request) => {
    const url = new URL(request.url())
    if (url.protocol.startsWith('http') && url.origin !== new URL(page.url()).origin) thirdPartyPreviewRequests.push(url.origin)
  }
  page.on('request', recordPreviewRequest)
  await share.getByText('Link preview', { exact: true }).click()
  const linkPreview = share.getByRole('article', { name: 'Link preview card' })
  await expect(linkPreview.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await share.getByText('Edit link preview', { exact: true }).click()
  await expect(share.getByLabel('Allow search engines to index this form')).not.toBeChecked()
  const shareTitle = `Your next visit to Harbour Studio`
  await share.getByLabel('Share title', { exact: true }).fill(shareTitle)
  await share.getByLabel('Share description', { exact: true }).fill('Tell us about your visit.')
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeDisabled()
  const shareImage = await browserLogo(page)
  await share.getByLabel('Share image', { exact: true }).setInputFiles({ name: 'share.png', mimeType: 'image/png', buffer: shareImage })
  await expect(share.getByLabel('Share image alt text')).toBeVisible()
  await expect(share.getByRole('button', { name: 'Save link preview', exact: true })).toBeDisabled()
  await share.getByLabel('Share image alt text').fill('North Studio wordmark on a white background')
  await share.getByLabel('Allow search engines to index this form').check()
  await expect(linkPreview.getByRole('heading', { name: shareTitle, exact: true })).toBeVisible()
  await expect(linkPreview.getByRole('img', { name: 'North Studio wordmark on a white background' })).toBeVisible()
  await expect(linkPreview.getByRole('img', { name: 'North Studio wordmark on a white background' })).toHaveAttribute('src', /^data:image\/png;base64,/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: `test-results/${info.project.name}-authoring-link-preview-editor.png`, fullPage: true })
  await share.getByRole('button', { name: 'Save link preview', exact: true }).click()
  await expect(page.getByText('Link preview saved to the draft. Publish to apply it.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeEnabled()
  await expect(page.getByText('Unpublished changes', { exact: false })).toBeVisible()
  expect(unrelatedRouteLoads).toBe(0)
  await page.reload()
  await page.getByRole('button', { name: 'Share', exact: true }).click()
  unrelatedRouteLoads = 0
  await share.getByText('Link preview', { exact: true }).click()
  await share.getByText('Edit link preview', { exact: true }).click()
  await expect(share.getByLabel('Share title', { exact: true })).toHaveValue(shareTitle)
  await expect(share.getByLabel('Share description', { exact: true })).toHaveValue('Tell us about your visit.')
  await expect(share.getByLabel('Share image alt text')).toHaveValue('North Studio wordmark on a white background')
  await expect(share.getByLabel('Allow search engines to index this form')).toBeChecked()
  const storedImage = linkPreview.getByRole('img', { name: 'North Studio wordmark on a white background' })
  await expect(storedImage).toHaveAttribute('src', new RegExp(`^/api/app/flows/${flowId}/preview-image\\?key=`))
  await expect.poll(() => storedImage.evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
  const storedImageResponse = await page.request.get((await storedImage.getAttribute('src'))!)
  expect(storedImageResponse.headers()['content-type']).toBe('image/png')
  expect(await storedImageResponse.body()).toEqual(shareImage)
  await page.getByRole('button', { name: 'Publish', exact: true }).click()
  await expect(page.getByText('Published. New visitors see this version.', { exact: true })).toBeVisible()
  await expect(page.getByText('Unpublished changes', { exact: false })).toHaveCount(0)
  await share.getByText('Link preview', { exact: true }).click()
  await expect(linkPreview.getByRole('heading', { name: shareTitle, exact: true })).toBeVisible()
  await expect(linkPreview.getByText('Tell us about your visit.', { exact: true })).toBeVisible()
  await expect(storedImage).toHaveAttribute('src', new RegExp(`^/api/app/flows/${flowId}/preview-image\\?key=`))
  await expect.poll(() => storedImage.evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: `test-results/${info.project.name}-authoring-link-preview-published.png`, fullPage: true })
  page.off('request', recordPreviewRequest)
  expect(thirdPartyPreviewRequests).toEqual([])
  const publicUrl = await share.getByLabel('Public link', { exact: true }).inputValue()
  const embedCode = await share.getByLabel('Embed code').inputValue()
  expect((await page.request.get(publicUrl)).status()).toBe(200)
  const settings = await (await page.request.get('/api/app/workspace')).json()
  const host = new URL(page.url()).origin
  expect((await page.request.put('/api/app/workspace', { headers: appHeaders, data: { ...settings, embedAllowedOrigins: [host] } })).ok()).toBe(true)
  const embedUrl = /src="([^"]+)"/.exec(embedCode)![1]
  expect((await page.request.get(embedUrl, { headers: { Referer: `${host}/host-page`, 'Sec-Fetch-Dest': 'iframe' } })).status()).toBe(200)
  await page.getByRole('button', { name: 'Edit steps', exact: true }).click()
  await checkAuthoringLayout(page)
  await editor.getByLabel('Prompt', { exact: true }).fill('Changed after publication')
  await save()
  await expect(page.getByText('Unpublished changes', { exact: false })).toBeVisible()
  expect(unrelatedRouteLoads).toBe(0)
  await page.getByRole('link', { name: 'All flows', exact: true }).click()
  const card = page.locator('.flow-card').filter({ has: page.getByRole('heading', { name: title, exact: true }) })
  await expect(card).toBeVisible()
  await expect(card.getByText('Open', { exact: true })).toBeVisible()
  await expect(card.getByText('Unpublished changes')).toBeVisible()
  await checkAuthoringLayout(page)
  await page.screenshot({ path: `test-results/${info.project.name}-authoring-dashboard.png`, fullPage: true })
})
