import AxeBuilder from '@axe-core/playwright'
import { contract } from './contract'
import { expect } from './fixtures'
import { signInEmptyWorkspace } from './authoring-helpers'
import { surveyMonkeyDetails,surveyMonkeyResponses } from '../fixtures/form-import/surveymonkey'
import { readReviewStream } from '../../src/core/features/importing/review-stream'
contract('IMPORT-005','SurveyMonkey file-pair upload reviews every supported field and names the omitted elements',async({page},info)=>{
 const cdp=await page.context().newCDPSession(page)
 await cdp.send('Emulation.setCPUThrottlingRate',{rate:4})
 await signInEmptyWorkspace(page)
 await page.getByRole('link',{name:'Import a form',exact:true}).click()
 await page.getByRole('combobox',{name:'Source',exact:true}).selectOption('surveymonkey')
 await expect(page.getByText(/Upload the API v3 survey-details JSON/)).toBeVisible()
 await page.getByLabel('Form definition JSON',{exact:true}).setInputFiles({name:'survey-details.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(surveyMonkeyDetails))})
 await page.getByLabel('Responses-bulk JSON (required)',{exact:true}).setInputFiles({name:'responses-bulk.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(surveyMonkeyResponses))})
 const check=async(name:string)=>{await page.screenshot({path:info.outputPath(`${info.project.name}-${name}.png`),fullPage:true});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);expect((await new AxeBuilder({page}).analyze()).violations).toEqual([])}
 await check('surveymonkey-upload')
 const reviewed=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/app/imports/review'&&response.request().method()==='POST')
 await page.getByRole('button',{name:'Review import',exact:true}).click()
 const review=await readReviewStream(new Response(await (await reviewed).body()).body!)
 await expect(page.getByRole('heading',{name:'Review the mapping',exact:true})).toBeVisible()
 await expect(page.getByText(/4 questions · 3 valid response rows/)).toBeVisible()
 const report=page.getByRole('list',{name:'Field and logic mapping report'})
 await expect(report).toContainText('Unsupported matrix menus')
 await expect(report).toContainText('Service experience matrix')
 for(const label of ['Clarity','Speed','Support','Good','Needs work','Not used'])await expect(report).toContainText(label)
 const matrix=review.questions.find((question:any)=>question.prompt==='Service experience matrix')
 expect(matrix).toMatchObject({questionType:'matrix',required:false,settings:{matrixMode:'single',matrixRows:[{label:'Clarity'},{label:'Speed'},{label:'Support'}]}})
 await expect(report).toContainText('Later descriptive text')
 await expect(report).toContainText('Other write-in')
 await expect(report).toContainText('Source collector synthetic-pencil-201')
 await expect(page.getByRole('button',{name:'Import reviewed form',exact:true})).toBeDisabled()
 await check('surveymonkey-review')
 await report.getByRole('listitem').filter({hasText:'Service experience matrix'}).filter({hasText:'Question retained'}).scrollIntoViewIfNeeded()
 await page.screenshot({path:info.outputPath(`${info.project.name}-matrix-review.png`)})
 expect(await (await page.request.get('/api/app/imports')).json()).toEqual([])
 await page.getByRole('checkbox',{name:/I have reviewed every changed or unsupported/}).check()
 await page.getByRole('button',{name:'Import reviewed form',exact:true}).click()
 await expect(page.getByRole('heading',{name:/Ready to verify/})).toBeVisible()
 await page.getByRole('button',{name:'Continue import',exact:true}).click()
 await expect(page.getByRole('link',{name:'Open the imported draft',exact:true})).toBeVisible({timeout:60_000})
 const ledger=await (await page.request.get(`/api/app/flows/${review.flowId}/ledger`)).json()
 const [clarity,speed,support]=matrix.settings.matrixRows.map((row:any)=>row.id), [good,needsWork,unused]=matrix.choices.map((choice:any)=>choice.id)
 expect([...ledger.responses].sort((a:any,b:any)=>a.completedAt.localeCompare(b.completedAt)).map((row:any)=>row.answers.find((answer:any)=>answer.stepId===matrix.id)?.value)).toEqual([{[clarity]:good,[speed]:needsWork},{[clarity]:unused,[support]:unused},undefined])
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('button',{name:'Undo import',exact:true}).click()
 await expect(page.getByRole('heading',{name:/^undone/})).toBeVisible({timeout:60_000})
 expect((await page.request.get(`/api/app/flows/${review.flowId}/draft`)).status()).toBe(404)
})
