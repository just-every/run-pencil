import AxeBuilder from '@axe-core/playwright'
import { expect, test } from './fixtures'
import { contract } from './contract'
import { signInEmptyWorkspace } from './authoring-helpers'
import { mkdir, writeFile } from 'node:fs/promises'
import type { Locator } from '@playwright/test'

contract(['FLOW-004', 'FLOW-005', 'FLOW-014', 'RESP-003', 'DIST-001', 'HOME-001', 'WS-003', 'BASE-PUBLIC-003'], 'plain corrections, compact editing and publication remain visible and accessible', async ({ page }, info) => {
  test.setTimeout(120_000)
  const output = process.env.PENCIL_CAPTURE_DIR ?? 'test-results/review-captures'
  await mkdir(output, { recursive: true })
  const measurements: Array<{ name: string; viewportHeights: number; horizontalOverflow: boolean; seriousOrCritical: number }> = []
  const reachable = async (control: Locator, keyboard = true) => {
    await expect(control).toBeVisible()
    // Centre it: a nearest-edge scroll lands on whole pixels, so a box at a fractional position stays a fraction clipped.
    await control.evaluate(element => element.scrollIntoView({ block: 'center', inline: 'nearest' }))
    await expect(control).toBeInViewport({ ratio: 1 })
    if (keyboard && await control.isEnabled()) {
      await control.click({ trial: true })
      expect(await control.evaluate(element => (element as HTMLElement).tabIndex)).toBeGreaterThanOrEqual(0)
      await control.focus()
      await expect(control).toBeFocused()
      // Direct focus anchors the round trip; native Tab must return to the control.
      await page.keyboard.press('Shift+Tab')
      await expect(control).not.toBeFocused()
      await page.keyboard.press('Tab')
      await expect(control).toBeFocused()
      await expect(control).toBeInViewport({ ratio: 1 })
      await control.click({ trial: true })
    } else if (!keyboard) {
      expect(await control.evaluate(element => {
        const box = element.getBoundingClientRect()
        const hit = document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2)
        return hit === element || element.contains(hit)
      })).toBe(true)
    }
  }
  const check = async (name: string) => {
    expect.soft(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    // Editing and preview controls must stay reachable as operator navigation grows.
    if (info.project.name === 'mobile' && await page.locator('.flow-authoring').count()) {
      const settings = page.getByRole('complementary', { name: 'Step settings', includeHidden: true })
      await expect(settings).toHaveCount(1)
      await expect(page.getByRole('complementary', { name: 'Flow steps', includeHidden: true })).toHaveCount(1)
      await expect(page.getByLabel('Draft question canvas')).toHaveCount(1)
      await reachable(page.getByRole('button', { name: 'Preview draft', exact: true }))
      await reachable(page.getByRole('button', { name: 'Publish', exact: true }))
      if (!await page.getByRole('region', { name: 'Share this flow' }).count()) {
        await expect(settings).toBeVisible()
        await expect(page.getByRole('complementary', { name: 'Flow steps' })).toBeVisible()
        await expect(page.getByLabel('Draft question canvas')).toBeVisible()
        await reachable(settings.getByLabel('Prompt', { exact: true }))
        await reachable(settings.getByRole('button', { name: 'Save', exact: true }))
        const canvas = page.getByLabel('Draft question canvas')
        // Answer groups expose their selected radio or current roving Tab entry.
        const selectedRadio = canvas.getByRole('radio', { checked: true })
        await reachable(await selectedRadio.count() ? selectedRadio : canvas.locator('button:not([tabindex="-1"]), input, textarea, select').first())
      }
      const discard = page.getByRole('button', { name: 'Discard changes', exact: true })
      if (await discard.count()) await reachable(discard)
      const preview = page.getByRole('region', { name: 'Draft preview' })
      if (await preview.count()) {
        await expect(preview).toHaveCount(1)
        await reachable(preview.getByRole('button', { name: 'Continue preview', exact: true }))
        await reachable(preview.getByRole('button', { name: 'Inspect answer path', exact: true }))
        await reachable(preview.getByRole('button', { name: 'Close preview', exact: true }))
      }
    }
    const violations = (await new AxeBuilder({ page }).analyze()).violations.filter(v => v.impact === 'serious' || v.impact === 'critical')
    expect.soft(violations).toEqual([])
    measurements.push({ name, viewportHeights: await page.evaluate(() => document.documentElement.scrollHeight / innerHeight), horizontalOverflow: await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), seriousOrCritical: violations.length })
    await writeFile(`${output}/${info.project.name}-measurements.json`, JSON.stringify(measurements, null, 2))
    expect.soft(await page.locator('body').innerText()).not.toMatch(/distinct stable|stable values|AI_PROVIDER|TASK_PROVIDER|Queued is not sent/i)
    await page.screenshot({ path: `${output}/${info.project.name}-${name}.png`, fullPage: true })
  }
  await signInEmptyWorkspace(page)
  const feedback = page.getByRole('button', { name: 'Customer feedback', exact: true })
  const nps = page.getByRole('button', { name: 'NPS', exact: true })
  await feedback.click()
  await page.mouse.move(0, 0)
  await expect(feedback).toHaveAttribute('aria-pressed', 'true')
  await expect.soft.poll(() => feedback.evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe(await nps.evaluate(el => getComputedStyle(el).backgroundColor))
  const filter = page.getByRole('navigation', { name: 'Filter flows' })
  expect.soft(await filter.getByRole('button', { name: 'All flows', exact: true }).evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe(await filter.getByRole('button', { name: 'Open', exact: true }).evaluate(el => getComputedStyle(el).backgroundColor))
  await check('template-selected')
  await page.getByRole('button', { name: 'Create draft flow' }).click()
  const editor = page.getByRole('complementary', { name: 'Step settings' })
  const rail = page.getByRole('complementary', { name: 'Flow steps' })
  await expect(editor.getByLabel('Choice 3 label')).toBeVisible()
  const flowId = /flows\/([^/]+)\//.exec(page.url())![1]
  const canvas = page.getByLabel('Draft question canvas')
  await editor.getByLabel('Question type').selectOption('multiple_choice')
  await canvas.getByRole('option').nth(0).click()
  await canvas.getByRole('option').nth(1).click()
  await expect(canvas.getByRole('option', { selected: true })).toHaveCount(2)
  await check('multiple-choice-selected')
  await editor.getByLabel('Question type').selectOption('priority')
  await expect(canvas.getByRole('checkbox', { checked: true })).toHaveCount(0)
  await expect(canvas.getByRole('checkbox', { checked: false })).toHaveCount(3)
  await expect(editor.getByLabel('Choice 3 label')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Preview draft', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeDisabled()
  await expect(editor.getByRole('button', { name: 'Save', exact: true })).toHaveCount(1)
  await check('priority-unselected')
  await canvas.getByRole('checkbox').first().focus()
  await page.keyboard.press('Space')
  await expect(canvas.getByRole('checkbox', { checked: true })).toHaveCount(1)
  await editor.getByLabel('Question type').selectOption('multiple_choice')
  await expect(canvas.getByRole('option', { selected: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(editor.getByLabel('Question type')).toHaveValue('single_choice')
  const draft = await (await page.request.get(`/api/app/flows/${flowId}/draft`)).json()
  await editor.getByRole('button', { name: 'Add rule' }).click()
  const answerPath = editor.getByLabel('Answer', { exact: true })
  const destination = editor.getByRole('combobox', { name: 'Then go to', exact: true })
  await answerPath.selectOption({ index: await answerPath.locator('option').count() - 1 })
  await destination.selectOption({ index: await destination.locator('option').count() - 1 })
  const pendingAnswer = await answerPath.inputValue()
  const pendingDestination = await destination.inputValue()
  expect(pendingAnswer).not.toBe('')
  expect(pendingDestination).not.toBe('')
  await check('branch')
  const steps = rail.locator('.step-list')
  expect.soft(await steps.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await editor.getByRole('button', { name: 'Choice', exact: true }).click()
  await editor.getByLabel('Choice 4 label').fill('Great')
  await editor.getByLabel('Prompt', { exact: true }).fill('Unaccepted changed prompt')
  await reachable(editor.getByRole('button', { name: 'Save', exact: true }))
  await page.keyboard.press('Enter')
  await expect(page.getByRole('alert')).toBeVisible()
  expect.soft(await page.getByRole('alert').innerText()).toBe('Each choice needs a different label.')
  expect(await (await page.request.get(`/api/app/flows/${flowId}/draft`)).json()).toEqual(draft)
  await expect(editor.getByLabel('Choice 4 label')).toHaveValue('Great')
  await expect(editor.getByLabel('Prompt', { exact: true })).toHaveValue('Unaccepted changed prompt')
  await expect(answerPath).toHaveValue(pendingAnswer)
  await expect(destination).toHaveValue(pendingDestination)
  await reachable(page.getByRole('alert'), false)
  await reachable(editor.getByLabel('Choice 4 label'))
  await check('duplicate-label')
  await reachable(page.getByRole('button', { name: 'Discard changes', exact: true }))
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Publish', exact: true }).click()
  const notice = page.getByText('Published. New visitors see this version.', { exact: true })
  const share = page.getByRole('region', { name: 'Share this flow' })
  await expect(notice).toBeVisible()
  const noticeBox = (await notice.boundingBox())!
  const shareBox = (await share.boundingBox())!
  expect.soft(noticeBox.y + noticeBox.height).toBeLessThanOrEqual(shareBox.y)
  if (info.project.name === 'desktop') expect.soft(noticeBox.y + noticeBox.height).toBeLessThan(900)
  await check('published')
  const publicUrl = await share.getByLabel('Public link', { exact: true }).inputValue()
  const builderUrl = page.url()
  await page.goto(publicUrl)
  await expect(page.locator('.respondent-shell[data-hydrated=true]')).toBeVisible()
  expect.soft(await page.locator('body').innerText()).not.toMatch(/aurora|cafe|café/i)
  await check('public')
  await page.goto(builderUrl.replace('/builder', '/results'))
  await expect(page.getByRole('heading', { name: 'Starts by device class' })).toBeVisible()
  await expect(page.getByText(/AI analysis and external task delivery are unavailable/)).toHaveCount(0)
  await check('results')
  await page.goto('/app')
  await expect(page.locator('.operator-shell[data-hydrated=true]')).toBeVisible()
  await page.getByRole('button', { name: 'New flow', exact: true }).click()
  await page.getByRole('button', { name: 'NPS', exact: true }).click()
  await page.getByRole('button', { name: 'Create draft flow' }).click()
  await expect(editor.getByLabel('Question type')).toHaveValue('nps')
  for (let score = 0; score <= 10; score++) expect.soft(await canvas.getByRole('radio', { name: String(score), exact: true }).locator('..').innerText()).toBe(String(score))
  await expect(canvas.getByRole('radio', { checked: false })).toHaveCount(11)
  await expect(canvas.getByText('Not at all likely', { exact: true })).toBeVisible()
  await expect(canvas.getByText('Extremely likely', { exact: true })).toBeVisible()
  await canvas.getByRole('radio', { name: '8', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(canvas.getByRole('radio', { name: '8', exact: true })).toBeChecked()
  await page.keyboard.press('ArrowRight')
  await expect(canvas.getByRole('radio', { name: '8', exact: true })).not.toBeChecked()
  await expect(canvas.getByRole('radio', { name: '9', exact: true })).toBeChecked()
  await expect(canvas.getByRole('radio', { checked: true })).toHaveCount(1)
  await check('nps')
  // An explicit generic rating edit preserves numeric-button and star proof.
  await editor.getByLabel('Question type').selectOption('rating')
  await editor.getByLabel('Start at', { exact: true }).selectOption('0')
  await editor.getByLabel('Number of steps', { exact: true }).selectOption('11')
  for (let score = 0; score <= 10; score++) expect.soft(await canvas.getByRole('radio', { name: `${score} out of 10`, exact: true }).innerText()).toBe(String(score))
  await expect(canvas.getByRole('radio', { checked: false })).toHaveCount(11)
  await canvas.getByRole('radio', { name: '8 out of 10', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(canvas.getByRole('radio', { name: '8 out of 10', exact: true })).toHaveAttribute('aria-checked', 'true')
  await canvas.getByRole('radio', { name: '9 out of 10', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(canvas.getByRole('radio', { name: '8 out of 10', exact: true })).toHaveAttribute('aria-checked', 'false')
  await expect(canvas.getByRole('radio', { checked: true })).toHaveCount(1)
  await check('rating')
  await editor.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Preview draft', exact: true })).toBeEnabled()
  await editor.getByLabel('Question type').selectOption('short_text')
  await expect(canvas.getByRole('textbox')).toHaveValue('')
  await editor.getByLabel('Question type').selectOption('rating')
  await expect(canvas.getByRole('radio', { checked: true })).toHaveCount(0)
  await expect(canvas.getByRole('radio', { checked: false })).toHaveCount(5)
  await canvas.getByRole('radio', { name: '3 out of 5', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(canvas.getByRole('radio', { name: '3 out of 5', exact: true })).toHaveAttribute('aria-checked', 'true')
  await check('rating-stars')
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(canvas.getByRole('radio', { checked: false })).toHaveCount(11)
  await page.getByRole('button', { name: 'Preview draft', exact: true }).click()
  const preview = page.getByRole('region', { name: 'Draft preview' })
  await expect(preview.getByRole('radio', { name: /^\d+ out of 10$/, checked: false })).toHaveCount(11)
  await preview.getByRole('radio', { name: '7 out of 10', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(preview.getByRole('radio', { name: '7 out of 10', exact: true })).toHaveAttribute('aria-checked', 'true')
  await expect(preview.getByRole('radio', { checked: true })).toHaveCount(1)
  await expect(canvas.getByRole('radio', { checked: true })).toHaveCount(0)
  await check('rating-preview')
  await reachable(preview.getByRole('button', { name: 'Close preview', exact: true }))
  await page.keyboard.press('Enter')
  await expect(preview).toHaveCount(0)
  await reachable(editor.getByLabel('Prompt', { exact: true }))
  // Every wrapped step remains part of ordinary keyboard navigation.
  const stepButtons = rail.locator('.step-button')
  await reachable(stepButtons.first())
  for (let index = 1; index < await stepButtons.count(); index++) {
    await page.keyboard.press('Tab')
    await expect(stepButtons.nth(index)).toBeFocused()
    await expect(stepButtons.nth(index)).toBeInViewport({ ratio: 1 })
  }
})
