import { expect } from './fixtures'
import { contract } from './contract'
import { signInEmptyWorkspace, checkAuthoringLayout } from './authoring-helpers'

contract('TMPL-002','save and reuse a team form, then retire its template',async({page},info)=>{
  await signInEmptyWorkspace(page)
  await page.getByRole('button',{name:'Customer feedback',exact:true}).click()
  await page.getByRole('button',{name:'Create draft flow'}).click()
  await expect(page.getByRole('heading',{name:'Customer feedback',exact:true})).toBeVisible()
  await page.getByText('Publication options',{exact:true}).click()
  await page.getByRole('button',{name:'Save as team template'}).click()
  await page.getByLabel('Template name',{exact:true}).fill('Post-visit client survey')
  await page.getByRole('form',{name:'Save team template'}).screenshot({path:`test-results/${info.project.name}-team-template-form.png`})
  await page.getByRole('button',{name:'Save template',exact:true}).click()
  await expect(page.getByText('Team template saved. Find it under New flow.')).toBeVisible()
  await page.getByRole('region',{name:'Team template',exact:true}).screenshot({path:`test-results/${info.project.name}-team-template-saved.png`})
  await page.getByText('Publication options',{exact:true}).click()
  await checkAuthoringLayout(page)
  await page.getByRole('link',{name:'All flows',exact:true}).click()
  await page.getByRole('button',{name:'New flow',exact:true}).click()
  await page.getByLabel('Workspace template').selectOption({label:'Post-visit client survey'})
  await expect(page.getByLabel('Flow name',{exact:true})).toHaveValue('Post-visit client survey')
  await checkAuthoringLayout(page)
  await page.screenshot({path:`test-results/${info.project.name}-team-template-picker.png`,fullPage:true})
  await page.getByRole('button',{name:'Create draft flow'}).click()
  await expect(page.getByRole('heading',{name:'Post-visit client survey',exact:true})).toBeVisible()
  await expect(page.getByRole('textbox',{name:'Prompt',exact:true})).toHaveValue('How was your visit?')
  await page.getByRole('button',{name:'Publish',exact:true}).click()
  await expect(page.getByRole('region',{name:'Share this flow'})).toBeVisible()
  await page.getByRole('link',{name:'All flows',exact:true}).click()
  await page.getByRole('button',{name:'New flow',exact:true}).click()
  await page.getByLabel('Workspace template').selectOption({label:'Post-visit client survey'})
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Retire template',exact:true}).click()
  await expect(page.getByLabel('Workspace template')).toHaveCount(0)
  await page.screenshot({path:`test-results/${info.project.name}-team-template-retired.png`,fullPage:true})
})
