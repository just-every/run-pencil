import type { Page } from '@playwright/test'
import { expect, openMailLink } from './fixtures'
import type { ScenarioCall } from '../results-scenario'
import { collectSharedReportScenario } from '../shared-report-scenario'
import type { SavedViewDetail, SavedReportShare, SharedReport } from '../../src/core/features/reporting/savedModel'
import { appHeaders } from './api-headers'

type ShareResult = { share: SavedReportShare; token: string; url: string }
export async function savedReportsJourney(page: Page, call: ScenarioCall, slug: string, capture: (name: string) => Promise<void>) {
  const scenario = await collectSharedReportScenario(call, slug)
  const rowCode = await call<{ id: string }>('/api/app/codes', { label: 'Needs guidance' })
  const columnCode = await call<{ id: string }>('/api/app/codes', { label: 'Requests follow-up' })
  for (const id of scenario.exposedIds) for (const code of [rowCode, columnCode]) await call(`/api/app/responses/${id}/answers/${scenario.textId}/codes/${code.id}`, undefined, 'PUT')
  await page.goto(`/app/flows/${scenario.flow.id}/results`)
  await page.getByLabel('Published revision').selectOption(scenario.revisionId)
  const cross = page.locator('section.crosstab')
  await cross.getByRole('combobox', { name: 'Rows', exact: true }).selectOption({ label: 'Plan' })
  await cross.getByRole('combobox', { name: 'Columns', exact: true }).selectOption({ label: 'Renewal' })
  await cross.getByRole('button', { name: 'Cross', exact: true }).click()
  await expect(cross.getByRole('row', { name: /^Scale/ })).toContainText('suppressed')
  const saved = page.locator('details.saved-reports')
  await saved.locator(':scope > summary').click()
  await saved.getByText('Compared cohorts', { exact: true }).click()
  const ledger = page.getByRole('region', { name: 'Response ledger', exact: true })
  await ledger.getByRole('combobox', { name: 'Collector', exact: true }).selectOption(scenario.subsetCollectorId)
  await saved.getByLabel('Comparison name', { exact: true }).fill('Collector comparison')
  await saved.getByRole('button', { name: 'Add current cohort', exact: true }).click()
  await ledger.getByRole('combobox', { name: 'Collector', exact: true }).selectOption('')
  await cross.getByRole('combobox', { name: 'Rows', exact: true }).selectOption(`question:${scenario.multiId}`)
  await cross.getByRole('button', { name: 'Cross', exact: true }).click()
  await expect(cross.getByText('Multiple select', { exact: true })).toBeVisible()
  await expect(saved.getByText('2 crosstabs included', { exact: true })).toBeVisible()
  await ledger.getByRole('combobox', { name: 'Source', exact: true }).selectOption('direct')
  await saved.getByRole('group', { name: 'Chosen charts' }).getByLabel('Plan', { exact: true }).check()
  await saved.getByRole('group', { name: 'Chosen charts' }).getByLabel('Renewal', { exact: true }).check()
  await saved.getByText('Add a code crosstab', { exact: true }).click()
  await saved.getByLabel('Row code', { exact: true }).selectOption(rowCode.id)
  await saved.getByLabel('Column code', { exact: true }).selectOption(columnCode.id)
  await saved.getByRole('button', { name: 'Include code crosstab', exact: true }).click()
  await saved.getByLabel('View name', { exact: true }).fill('Renewal dashboard view')
  const pending = page.waitForResponse(response => new URL(response.url()).pathname === scenario.path + '/saved-views' && response.request().method() === 'POST')
  await saved.getByRole('button', { name: 'Save current view', exact: true }).click()
  const created = await (await pending).json() as SavedViewDetail
  expect(created.view.definition.filter.source).toBe('direct')
  expect(created.view.definition.crosstabs).toHaveLength(3)
  expect(created.view.definition.charts).toEqual([scenario.planId, scenario.renewalId])
  const opened = saved.getByRole('region', { name: 'Opened saved view', exact: true })
  await expect(opened.getByText('Responses', { exact: false }).first()).toBeVisible()
  await expect(opened.getByText('8 of 43 answers', { exact: true })).toBeVisible()
  await expect(opened.getByText(/suppressed cell would be recoverable/).first()).toBeVisible()
  await expect(opened.getByText(/This subset cohort/)).toBeVisible()
  await capture('saved-view')
  const expectedText = await opened.locator('article.saved-report').innerText()

  const operators = await call<Array<{ id: string; email: string; displayName: string }>>('/api/app/operators')
  const currentEmail = operators.find(operator => operator.id === created.view.savedBy.id)!.email
  const otherEmail = currentEmail.replace('@', '+reports@')
  await call('/api/app/operators', { email: otherEmail, displayName: 'Report reviewer' })
  await page.context().clearCookies()
  await page.goto('/signin'); await page.getByLabel('Operator email').fill(otherEmail)
  await page.getByRole('button', { name: /Send.*link/i }).click(); await openMailLink(page, otherEmail)
  await page.getByRole('button', { name: 'Confirm', exact: true }).click()
  await page.goto(`/app/flows/${scenario.flow.id}/results`)
  await saved.locator(':scope > summary').click()
  await saved.getByRole('list', { name: 'Saved views', exact: true }).getByRole('button', { name: created.view.name, exact: true }).click()
  await expect(opened.locator('article.saved-report')).toHaveText(expectedText.replace(/\s+/g, ' ').trim(), { useInnerText: true })
  expect(await call<SavedViewDetail>('/api/app/saved-views/' + created.view.id)).toEqual(created)
  await expect(opened.getByText(`Saved by ${created.view.savedBy.name}`, { exact: false })).toBeVisible()
  await capture('saved-other-operator')

  const second = await call<SavedViewDetail>(scenario.path + '/saved-views', { ...created.view.definition, name: 'Scale responses', filter: { answerStepId: scenario.planId, answerValue: scenario.scaleId }, cohorts: [] })
  await page.reload(); await saved.locator(':scope > summary').click()
  await saved.getByText('Arrange a dashboard', { exact: true }).click()
  await saved.getByLabel('Dashboard name', { exact: true }).fill('Renewal board')
  await saved.getByRole('group', { name: 'Views in this dashboard' }).getByLabel(created.view.name, { exact: true }).check()
  await saved.getByRole('group', { name: 'Views in this dashboard' }).getByLabel(second.view.name, { exact: true }).check()
  await saved.getByRole('button', { name: 'Move view 2 earlier', exact: true }).click()
  await saved.getByRole('button', { name: 'Save dashboard', exact: true }).click()
  await expect(saved.getByRole('button', { name: 'New dashboard', exact: true })).toBeVisible()
  await expect(saved.locator('ol.report-list li > span')).toHaveText([second.view.name, created.view.name])
  await capture('dashboard')
  await saved.getByRole('button', { name: 'New dashboard', exact: true }).click()
  await saved.getByLabel('Dashboard name', { exact: true }).fill('Program renewal board')
  await saved.getByLabel('Dashboard scope', { exact: true }).selectOption('program')
  await saved.getByRole('group', { name: 'Views in this dashboard' }).getByLabel(created.view.name, { exact: true }).check()
  await saved.getByRole('group', { name: 'Views in this dashboard' }).getByLabel(second.view.name, { exact: true }).check()
  const programSaved = page.waitForResponse(response => new URL(response.url()).pathname === '/api/app/report-dashboards' && response.request().method() === 'POST')
  await saved.getByRole('button', { name: 'Save dashboard', exact: true }).click()
  expect(await (await programSaved).json()).toMatchObject({ scope: 'program', flowId: null, viewIds: [created.view.id, second.view.id] })
  await capture('program-dashboard')

  await saved.getByRole('list', { name: 'Saved views', exact: true }).getByRole('button', { name: created.view.name, exact: true }).click()
  await opened.getByText('Share this report', { exact: true }).click()
  const sharedResponse = page.waitForResponse(response => new URL(response.url()).pathname === `/api/app/saved-views/${created.view.id}/shares` && response.request().method() === 'POST')
  await opened.getByRole('button', { name: 'Create report link', exact: true }).click()
  const shared = await (await sharedResponse).json() as ShareResult
  const anonymous = await page.context().browser()!.newContext({ viewport: page.viewportSize()!, extraHTTPHeaders: { 'CF-Connecting-IP': '198.19.202.1' } })
  const reader = await anonymous.newPage()
  const captureReader = async (name: string) => {
    if (!process.env.PENCIL_CAPTURE_DIR) return
    const { mkdir } = await import('node:fs/promises'); const { join } = await import('node:path')
    await mkdir(process.env.PENCIL_CAPTURE_DIR, { recursive: true })
    await reader.screenshot({ path: join(process.env.PENCIL_CAPTURE_DIR, `${page.viewportSize()!.width}-report-${name}.png`), fullPage: true })
  }
  try {
    const base = new URL(page.url()).origin
    expect((await reader.goto(base + shared.url))!.status()).toBe(200)
    const publicReport = reader.getByRole('article', { name: `Report: ${created.view.name}`, exact: true })
    await expect(publicReport.getByText('8 of 43 answers', { exact: true })).toBeVisible()
    await expect(publicReport.getByText('Responses', { exact: false }).first()).toContainText('43')
    await expect(publicReport.getByText(/suppressed cell would be recoverable/).first()).toBeVisible()
    await expect(publicReport.getByText(/This subset cohort/)).toBeVisible()
    await expect(publicReport.getByRole('region', { name: 'Saved crosstab table' })).toContainText('43')
    const apiResponse = await reader.request.get(base + `/api/public/reports/${shared.token}`)
    expect(apiResponse.status()).toBe(200); expect(apiResponse.headers()['set-cookie']).toBeUndefined()
    const report = await apiResponse.json() as SharedReport
    expect(report).toEqual(created.report)
    const serialized = JSON.stringify(report)
    for (const value of [...scenario.receipts, scenario.identityFieldId, scenario.identityValue, scenario.excerpt, scenario.rareValue]) {
      expect(serialized).not.toContain(value); expect(await reader.content()).not.toContain(value)
    }
    expect(await anonymous.cookies()).toEqual([])
    expect(await reader.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(await reader.locator('main').evaluate(root => [...root.querySelectorAll('*')].filter(element => element.textContent?.trim() && element.getClientRects().length).every(element => parseFloat(getComputedStyle(element).fontSize) >= 13))).toBe(true)
    await publicReport.getByText('About this report’s protection', { exact: true }).click()
    await expect(publicReport.getByText(/separate links/)).toBeVisible()
    await captureReader('open')
    await call('/api/app/analysis/policies', { autorunEnabled: true, autorunMinimum: 5, selection: 'highest-impact', disclosureThreshold: 1 }, 'PUT')
    await reader.reload(); expect(await (await reader.request.get(base + `/api/public/reports/${shared.token}`)).json()).toEqual(report)
    await expect(publicReport.getByText(/suppressed cell would be recoverable/).first()).toBeVisible()
    const raw = await call<{ responses: Array<{ id: string }> }>(scenario.path + '/responses/export?' + new URLSearchParams(scenario.filter))
    expect(raw.responses.map(response => response.id).sort()).toEqual([...scenario.exposedIds].sort())
    const operatorCross = await call<{ cells: Array<Array<{ count?: number; suppressed: boolean }>> }>(scenario.path + '/crosstab?' + new URLSearchParams({ revisionId: scenario.revisionId, rows: `question:${scenario.planId}`, columns: `question:${scenario.renewalId}` }))
    expect(operatorCross.cells[2][0]).toMatchObject({ count: 3, suppressed: false })

    await opened.getByLabel('Report password (optional)', { exact: true }).fill('synthetic-pencil-26')
    await opened.getByLabel('Link expiry (optional)', { exact: true }).fill(new Date(Date.now() + 86400000).toISOString().slice(0, 16))
    const protectedPending = page.waitForResponse(response => new URL(response.url()).pathname === `/api/app/saved-views/${created.view.id}/shares` && response.request().method() === 'POST')
    await opened.getByRole('button', { name: 'Create report link', exact: true }).click()
    const protectedShare = await (await protectedPending).json() as ShareResult
    await reader.goto(base + protectedShare.url)
    await expect(reader.getByLabel('Report password', { exact: true })).toBeVisible()
    await captureReader('password')
    await reader.getByLabel('Report password', { exact: true }).fill('synthetic-pencil-27')
    await reader.getByRole('button', { name: 'Open report', exact: true }).click(); await expect(reader.getByRole('alert')).toBeVisible()
    await expect(reader.getByRole('article')).toHaveCount(0)
    await reader.getByLabel('Report password', { exact: true }).fill('synthetic-pencil-26')
    await reader.getByRole('button', { name: 'Open report', exact: true }).click()
    await expect(publicReport.getByText('8 of 43 answers', { exact: true })).toBeVisible()
    expect(await anonymous.cookies()).toEqual([])
    await opened.locator('li').filter({ hasText: 'Link access' }).getByRole('button', { name: 'Revoke link', exact: true }).click()
    expect((await reader.goto(base + shared.url))!.status()).toBe(404)
    await expect(reader.getByRole('heading', { name: 'Report not found' })).toBeVisible()
    expect((await reader.request.get(base + `/api/public/reports/${shared.token}`)).status()).toBe(404)
    await captureReader('revoked')
    const refused = await reader.request.post(base + scenario.path + '/saved-views', { headers: appHeaders, data: created.view.definition })
    expect(refused.status()).toBe(401)
  } finally { await anonymous.close(); await call('/api/app/analysis/policies', { autorunEnabled: true, autorunMinimum: 5, selection: 'highest-impact', disclosureThreshold: 5 }, 'PUT') }
}
