contract('FLOW-006', 'rejects all publication problems by stable ID without creating a revision and keeps the draft editable', async () => {
  const f = await foundationFixture('foundation-invalid-publication')
  await f.add({ kind: 'question', questionType: 'single_choice', prompt: 'Missing choices' })
  await expect(f.add({ kind: 'question', questionType: 'rating', prompt: 'Bad rating', questionSettings: { min: 5, max: 1 } })).rejects.toThrow('settings')
  await f.add({ kind: 'question', questionType: 'rating', prompt: 'Missing default path', questionSettings: { min: 1, max: 5 } })
  await f.add({ kind: 'completion', questionType: null, prompt: 'Done' })
  const editable = await f.draft()
  await f.services.flows.updateBuilderDraft({ ...f.flow, stepId: editable.steps[1].id, expectedVersion: editable.flow.draftVersion, prompt: editable.steps[1].prompt, required: false, nextStepId: null })
  const before = await f.draft()
  const rows = async () => (await env.DB.prepare('SELECT * FROM flow_revisions WHERE flow_id = ? ORDER BY id').bind(f.flow.flowId).all()).results
  const revisions = await rows()
  await expect(f.publish()).rejects.toMatchObject({ details: expect.arrayContaining(before.steps.slice(0, 2).map(s => expect.objectContaining({ stepId: s.id, reason: expect.any(String) }))) })
  expect(await rows()).toEqual(revisions)
  expect(await f.draft()).toEqual(before)
  expect(await f.services.flows.updateBuilderDraft({ ...f.flow, stepId: before.steps[0].id, expectedVersion: before.flow.draftVersion, prompt: 'Still editable', required: false })).toMatchObject({ kind: 'updated' })
}, 60_000)

contract(['RESP-006', 'RESP-010', 'FLOW-019'], 'retains no abandoned answers or identity, preserves deliberately entered email exactly and compares it without case sensitivity', async () => {
  const f = await foundationFixture('foundation-anonymous-email')
  await f.add({ kind: 'question', questionType: 'email', prompt: 'Your email', required: true })
  await f.add({ kind: 'completion', questionType: null, prompt: 'Done' }); await f.publish()
  const session = await f.start()
  const step = session.flow.steps[0]
  await f.services.responses.advancePublicSession({ slug: f.slug, sessionId: session.sessionId, sessionToken: session.sessionToken, stepId: step.id })
  expect(await fixtureExport(env.DB, f.scope.workspaceId, f.flow.flowId, {})).toMatchObject({ responses: [] })
  const rows = await env.DB.prepare('SELECT * FROM respondent_sessions WHERE id = ?').bind(session.sessionId).first()
  expect(Object.keys(rows!)).not.toContain('participant_id')
  expect(Object.keys(rows!).some(key => /answer|email|contact|address|agent|host/.test(key))).toBe(false)
  await f.mature(session.sessionId)
  const receipt = await f.final(session, [{ stepId: step.id, value: 'Mixed.Case@Example.test' }])
  const exported = await fixtureExport(env.DB, f.scope.workspaceId, f.flow.flowId, { answerStepId: step.id, answerValue: 'mixed.case@example.TEST' })
  expect(exported.responses).toHaveLength(1)
  expect(exported.responses[0].answers[0].value).toBe('Mixed.Case@Example.test')
  expect(JSON.stringify(exported)).not.toMatch(/participant|contact|sessionToken|deviceClass|addressHash/)
  const response = await env.DB.prepare('SELECT * FROM responses WHERE id = ?').bind(receipt.responseId).first()
  expect(response!.participant_id).toBeNull()
  expect(Object.keys(response!).some(key => /email|contact|address|device|agent|host/.test(key))).toBe(false)
}, 60_000)

contract('RESP-016', 'drops a honeypot with one anonymous defence audit and no response, answer, counter, session or outbox change', async () => {
  const f = await foundationFixture('foundation-honeypot')
  await f.add({ kind: 'question', questionType: 'short_text', prompt: 'Answer', required: true })
  await f.add({ kind: 'completion', questionType: null, prompt: 'Done' }); await f.publish()
  const session = await f.start()
  const tables = ['responses', 'response_answers', 'response_outbox', 'respondent_sessions', 'respondent_session_step_events', 'revision_metric_counters', 'revision_step_metric_counters']
  const snapshot = async () => (await env.DB.batch(tables.map(table => env.DB.prepare(`SELECT * FROM ${table} ORDER BY id`)))).map(result => result.results)
  const before = await snapshot()
  const receipt = await f.final(session, [{ stepId: session.flow.steps[0].id, value: 'do not retain this answer' }], 'bot')
  expect(receipt).toMatchObject({ disposition: 'dropped' })
  expect(await snapshot()).toEqual(before)
  const audit = await env.DB.prepare("SELECT actor_operator_id, subject_id, details_json, created_at FROM audit_entries WHERE kind = 'response.honeypot-dropped' AND workspace_id = ? ORDER BY created_at DESC LIMIT 1").bind(f.scope.workspaceId).first()
  expect(audit).not.toBeNull()
  expect(JSON.stringify(audit)).not.toContain('do not retain this answer')
  expect(audit!.actor_operator_id).toBeNull()
}, 60_000)

contract(['FLOW-001','FLOW-011','FLOW-015','DASH-002'], 'lifecycle preserves collected history while duplication creates an independent draft and fresh structure IDs', async () => {
  const f = await foundationFixture('foundation-lifecycle')
  await expect(f.services.flows.getPublicFlow(f.slug)).rejects.toThrow('not available')
  await f.add({ kind: 'question', questionType: 'single_choice', prompt: 'Pick one', required: true, choices: [{ value: 'one', label: 'One' }, { value: 'two', label: 'Two' }] })
  await f.add({ kind: 'completion', questionType: null, prompt: 'Done' })
  await f.publish()
  const old = await f.start(); await f.mature(old.sessionId)
  const done = await f.final(old, [{ stepId: old.flow.steps[0].id, value: old.flow.choices[0].id }])
  const draft = await f.draft()
  const copied = await f.services.flows.duplicateFlow({ ...f.flow, title: 'Independent copy', slug: 'foundation-lifecycle-copy' })
  const copy = await f.services.flows.getBuilderDraft(f.scope.workspaceId, copied.id)
  expect(copy.flow.status).toBe('draft')
  expect(copy.steps.map(s => [s.kind, s.questionType, s.prompt, s.helperText, s.required, s.questionSettings])).toEqual(draft.steps.map(s => [s.kind, s.questionType, s.prompt, s.helperText, s.required, s.questionSettings]))
  expect(copy.steps.every(s => !draft.steps.some(old => old.id === s.id))).toBe(true)
  expect(copy.choices.every(c => !draft.choices.some(old => old.id === c.id))).toBe(true)
  expect((await fixtureExport(env.DB, f.scope.workspaceId, copied.id, {})).responses).toEqual([])
  expect(await f.services.distribution.launches.list(f.scope.workspaceId, copied.id)).toEqual([])
  await f.services.flows.closeFlow(f.scope.workspaceId, f.flow.flowId, f.operatorId)
  await expect(f.services.flows.getPublicFlow(f.slug)).rejects.toThrow('no longer accepting')
  await f.services.flows.reopenFlow(f.scope.workspaceId, f.flow.flowId, f.operatorId)
  expect((await f.services.flows.getPublicFlow(f.slug)).revision.id).toBe(old.revisionId)
  await f.services.flows.archiveFlow(f.scope.workspaceId, f.flow.flowId, f.operatorId)
  await expect(f.services.flows.getPublicFlow(f.slug)).rejects.toThrow('not available')
  await expect(f.services.flows.reopenFlow(f.scope.workspaceId, f.flow.flowId, f.operatorId)).rejects.toThrow()
  expect((await f.services.flows.listDashboard(f.scope.workspaceId)).some(flow => flow.id === f.flow.flowId)).toBe(false)
  expect((await f.services.flows.listDashboard(f.scope.workspaceId, 'archived')).find(flow => flow.id === f.flow.flowId)).toMatchObject({ completedResponses: 1, starts: 1 })
  expect((await fixtureExport(env.DB, f.scope.workspaceId, f.flow.flowId, {})).responses.map(r => r.id)).toEqual([done.responseId])
  await f.services.flows.archiveFlow(f.scope.workspaceId, copied.id, f.operatorId)
  expect((await f.services.flows.getBuilderDraft(f.scope.workspaceId, copied.id)).flow.status).toBe('archived')
}, 60_000)

contract('WS-001', 'workspace zone changes cannot move an already published deadline or its recorded zone', async () => {
  const f = await foundationFixture('foundation-zone')
  await f.services.workspace.updateSettings({ ...f.scope, timeZone: 'Australia/Brisbane', sendingWindowStart: '09:00', sendingWindowEnd: '17:00' })
  await f.add({ kind: 'question', questionType: 'short_text', prompt: 'Feedback' })
  await f.add({ kind: 'completion', questionType: null, prompt: 'Done' })
  const deadline = '2080-02-01T07:00:00.000Z'
  const published = await f.services.flows.publishDraft({ ...f.flow, expectedVersion: (await f.draft()).flow.draftVersion, deadlineAt: deadline })
  expect(published.kind).toBe('published')
  if (published.kind !== 'published') throw new Error('Publication did not succeed')
  const before = await env.DB.prepare('SELECT deadline_at, deadline_time_zone FROM flow_revisions WHERE id = ?').bind(published.revision.id).first()
  expect(before).toEqual({ deadline_at: deadline, deadline_time_zone: 'Australia/Brisbane' })
  await f.services.workspace.updateSettings({ ...f.scope, timeZone: 'America/New_York', sendingWindowStart: '10:00', sendingWindowEnd: '18:00' })
  expect(await env.DB.prepare('SELECT deadline_at, deadline_time_zone FROM flow_revisions WHERE id = ?').bind(published.revision.id).first()).toEqual(before)
})
